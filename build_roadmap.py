# ---------------------------------------------------------------------------
# Build logic
# ---------------------------------------------------------------------------

def build_topic(parent: Path, topic) -> tuple[int, int]:
    """Recursively materialize a topic (file or subfolder).

    Returns (files_created, folders_created).
    """
    files_created = 0
    folders_created = 0

    if isinstance(topic, dict):
        (folder_name, items), = topic.items()
        folder_path = parent / sanitize_name(folder_name)
        if not folder_path.exists():
            folders_created += 1
        folder_path.mkdir(parents=True, exist_ok=True)
        for item in items:
            f, d = build_topic(folder_path, item)
            files_created += f
            folders_created += d
    elif isinstance(topic, str):
        file_path = parent / f"{sanitize_name(topic)}.md"
        if not file_path.exists():
            file_path.write_text(
                FILE_TEMPLATE.format(title=topic),
                encoding="utf-8",
            )
            files_created += 1
    else:
        raise TypeError(f"Unsupported topic type: {type(topic)!r}")

    return files_created, folders_created


def main() -> None:
    total_files = 0
    total_folders = 0
    stage_table_rows: list[str] = []

    for index, (stage_name, topics) in enumerate(ROADMAP, start=1):
        stage_folder_name = f"{index:02d}_{sanitize_name(stage_name)}"
        stage_path = ROOT / stage_folder_name

        if not stage_path.exists():
            total_folders += 1
        stage_path.mkdir(parents=True, exist_ok=True)

        for topic in topics:
            f, d = build_topic(stage_path, topic)
            total_files += f
            total_folders += d

        stage_table_rows.append(
            f"| {index:02d} | [{stage_name}](./{stage_folder_name}/) |"
        )

    # Write / refresh the root README.
    readme_path = ROOT / "README.md"
    readme_path.write_text(
        README_TEMPLATE.format(stage_table="\n".join(stage_table_rows)),
        encoding="utf-8",
    )

    print("[+] Cybersecurity roadmap architecture generated successfully.")
    print(f"    Root path        : {ROOT}")
    print(f"    Stages           : {len(ROADMAP)}")
    print(f"    New folders made : {total_folders}")
    print(f"    New files made   : {total_files}")
    print(f"    README written   : {readme_path}")


if __name__ == "__main__":
    main()
