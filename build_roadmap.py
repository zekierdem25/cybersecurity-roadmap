def sanitize_name(name: str) -> str:
    """Convert a topic name into a filesystem-safe identifier."""
    # Drop anything in parentheses (e.g. Turkish translations).
    name = re.sub(r"\([^)]*\)", "", name).strip()
    # Turkish -> English
    name = name.translate(TR_MAP)
    # Strip remaining diacritics / non-ASCII.
    name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode("ascii")
    # Replace special symbols with readable equivalents.
    for symbol, word in SYMBOL_WORDS.items():
        name = name.replace(symbol, word)
    # Replace remaining punctuation with whitespace.
    name = re.sub(r"[^\w\s-]", " ", name)
    # Collapse whitespace -> underscores.
    name = re.sub(r"\s+", "_", name.strip())
    # Collapse repeated underscores.
    name = re.sub(r"_+", "_", name)
    return name.strip("_")


